"""Security primitives shared by the authentication flows.

This module stays framework-free: it generates unpredictable tokens, compares them in constant
time, and hashes or verifies passwords with Argon2id. Cookie and header names live in
configuration.
"""

from __future__ import annotations

import hashlib
import secrets

from argon2 import PasswordHasher
from argon2.exceptions import InvalidHashError, VerificationError

from app.core.config import get_settings

# 32 bytes of entropy, rendered as a 43-character URL-safe string.
CSRF_TOKEN_BYTES = 32
SESSION_TOKEN_BYTES = 32


def generate_csrf_token() -> str:
    """Return a new URL-safe CSRF token."""

    return secrets.token_urlsafe(CSRF_TOKEN_BYTES)


def tokens_match(expected: str | None, provided: str | None) -> bool:
    """Compare two tokens in constant time.

    Missing or empty values never match. Encoding to bytes keeps the comparison safe for
    non-ASCII input, which ``compare_digest`` rejects for strings.
    """

    if not expected or not provided:
        return False
    return secrets.compare_digest(expected.encode("utf-8"), provided.encode("utf-8"))


def generate_session_token() -> str:
    """Return a new opaque, URL-safe session token for the cookie."""

    return secrets.token_urlsafe(SESSION_TOKEN_BYTES)


def hash_session_token(raw_token: str) -> str:
    """Return the SHA-256 hex digest stored in ``sessions.token_hash``.

    Only this digest reaches the database; the raw token exists only in the cookie.
    """

    return hashlib.sha256(raw_token.encode("utf-8")).hexdigest()


def _password_hasher() -> PasswordHasher:
    """Build a hasher from the current configuration.

    Building it per call keeps the cost parameters overridable by tests without process-wide
    mutable state.
    """

    settings = get_settings()
    return PasswordHasher(
        time_cost=settings.argon2_time_cost,
        memory_cost=settings.argon2_memory_cost,
        parallelism=settings.argon2_parallelism,
    )


def hash_password(password: str) -> str:
    """Hash a password with Argon2id using the configured cost parameters.

    A fresh random salt is generated by the library for every call. The returned string already
    contains the algorithm, parameters, salt, and digest, so no separate salt column is needed.
    """

    return _password_hasher().hash(password)


def verify_password(password: str, password_hash: str) -> bool:
    """Return whether ``password`` matches the stored Argon2id hash.

    A malformed or unsupported stored hash is treated as a mismatch. It must never turn into an
    unhandled server error or reveal which part of the credentials failed.
    """

    try:
        return _password_hasher().verify(password_hash, password)
    except (VerificationError, InvalidHashError):
        return False


def password_needs_rehash(password_hash: str) -> bool:
    """Return whether a stored hash uses weaker parameters than the current configuration."""

    try:
        return _password_hasher().check_needs_rehash(password_hash)
    except (InvalidHashError, ValueError):
        return False
